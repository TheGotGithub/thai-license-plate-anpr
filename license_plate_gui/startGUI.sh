#!/bin/bash
# เปิดหน้าเว็บ GUI สำหรับตรวจจับป้ายทะเบียน
# วิธีใช้: ./startGUI.sh  (รันจากที่ไหนก็ได้ ไม่ต้อง cd เข้าโฟลเดอร์นี้ก่อน)

set -e

# ============================================================
# ขั้นตอนที่ 1: หา path ของ venv (venv อยู่ที่ root ของโปรเจกต์ นอกโฟลเดอร์นี้)
# ============================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
VENV_DIR="$PROJECT_ROOT/venv"

# ============================================================
# ขั้นตอนที่ 2: เช็คว่ามี venv หรือยัง ถ้ายังไม่มีให้แจ้งเตือน
# ============================================================

if [ ! -d "$VENV_DIR" ]; then
    echo "ยังไม่มี venv กรุณารัน 'source $PROJECT_ROOT/setup.sh' ก่อนใช้งานครั้งแรก"
    exit 1
fi

# ============================================================
# ขั้นตอนที่ 3: เปิดหน้าเว็บ GUI ด้วย streamlit ใน venv
# ============================================================

echo "กำลังเปิดหน้าเว็บ GUI..."
"$VENV_DIR/bin/streamlit" run "$SCRIPT_DIR/app.py" "$@"
